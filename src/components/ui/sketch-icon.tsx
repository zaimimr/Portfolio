export type SketchIconName = keyof typeof icons;

export const sketchIconNames = Object.keys(icons) as SketchIconName[];

type SketchIconProps = {
  name: SketchIconName;
  size?: number;
  strokeWidth?: number;
  draw?: boolean;
  className?: string;
};

export function SketchIcon({
  name,
  size = 24,
  strokeWidth = 1.8,
  draw = false,
  className,
}: SketchIconProps) {
  const reducedMotion = useReducedMotion();
  const animated = draw && !reducedMotion;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={cn("shrink-0", className)}
    >
      {icons[name].map((d, index) =>
        animated ? (
          <motion.path
            key={d}
            d={d}
            initial={{ pathLength: 0 }}
            animate={{ pathLength: 1 }}
            transition={{
              duration: 0.6,
              delay: index * 0.1,
              ease: [0.22, 1, 0.36, 1],
            }}
          />
        ) : (
          <path key={d} d={d} />
        ),
      )}
    </svg>
  );
}
